import {chromium} from '../jev-use/node_modules/playwright/index.mjs';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
const origin='http://127.0.0.1:8769';
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1600,height:1000},userAgent:'Nexus QA NexusDesktop/1.0'});
const failures=[];
page.on('pageerror',e=>failures.push(e.message));
const assetMode=process.env.NEXUS_USE_INSTALLED_ASSETS==='1';
try {
 if(!assetMode) {
  for(const name of ['app.js','app.css']) await page.route('**/assets/'+name,r=>r.fulfill({path:fileURLToPath(new URL('./dist/'+name,import.meta.url))}));
 }
 const standalone=await page.request.get(origin+'/',{headers:{'User-Agent':'Ordinary browser'}});
 assert.equal(standalone.status(),404);
 await page.goto(origin+'/?theme=light#/observability');
 await page.getByTestId('observability').waitFor();
 await page.getByText('Monitor online',{exact:true}).waitFor();
 const live=await (await page.request.get(origin+'/runs')).json();
 if(live.length) await page.getByRole('button',{name:'Inspect call '+live[0].id,exact:true}).count();
 console.log('PASS live runtime: '+live.length+' recorded calls, desktop route renders');
 const now=Date.now();
 const fixture=Array.from({length:55},(_,i)=>({id:'qa-'+i,tool:i%2?'jev_browse':'find_files',status:i===1?'error':i===2?'running':'passed',started:now-120000+i*1500,ms:i===2?undefined:500+i*25,backend:i%2?'browser':'native',session:'qa-session',inputTokens:i%2?120:undefined,outputTokens:i%2?20:undefined}));
 let calls=fixture;
 let disconnected=false;
 await page.route('**/runs',r=>disconnected?r.fulfill({status:503,body:'Unavailable'}):r.fulfill({json:calls}));
 await page.reload();
 const list=page.getByTestId('waterfall-scroll');
 await list.getByRole('button',{name:'Inspect call qa-0',exact:true}).waitFor();
 assert.equal(await list.locator('tbody tr').count(),25);
 await page.getByRole('button',{name:'Next calls'}).click();
 await list.getByRole('button',{name:'Inspect call qa-25',exact:true}).waitFor();
 await page.getByRole('button',{name:'Previous calls'}).click();
 await page.getByRole('combobox',{name:'Status',exact:true}).selectOption('error');
 assert.equal(await list.locator('tbody tr').count(),1);
 await list.getByRole('button',{name:'Inspect call qa-1',exact:true}).click();
 const inspector=page.getByRole('complementary',{name:'Call inspector'});
 await inspector.getByRole('button',{name:'Timing',exact:true}).click();
 await inspector.getByText('Whole call only').waitFor();
 await inspector.getByRole('button',{name:'Usage',exact:true}).click();
 await inspector.getByText('120',{exact:true}).waitFor();
 await page.getByRole('button',{name:'Clear filters'}).click();
 await page.getByRole('textbox',{name:'Filter calls'}).fill('find_files');
 assert.ok(await list.locator('tbody tr').count()>0);
 assert.equal(await list.getByText('jev_browse',{exact:true}).count(),0);
 await page.getByRole('button',{name:'Clear filters'}).click();
 await page.getByRole('button',{name:'Pause live'}).click();
 calls=[];
 await page.waitForTimeout(2500);
 assert.equal(await list.locator('tbody tr').count(),25);
 await page.getByRole('button',{name:'Resume live'}).click();
 await list.getByText('No matching calls.',{exact:false}).waitFor();
 calls=fixture;
 await list.getByRole('button',{name:'Inspect call qa-0',exact:true}).waitFor();
 await page.getByRole('slider',{name:'Timeline end'}).fill('20');
 assert.ok(await list.locator('tbody tr').count()<25);
 await page.getByRole('button',{name:'Reset range'}).click();
 await page.getByRole('button',{name:'Sort by Duration'}).click();
 assert.equal(await list.getByRole('button',{name:'Inspect call qa-54',exact:true}).count(),1);
 await page.getByRole('button',{name:'Sort by Started'}).click();
 await list.getByRole('button',{name:'Inspect call qa-1',exact:true}).click();
 await page.screenshot({path:fileURLToPath(new URL('../docs/screenshots/observability-light.png',import.meta.url))});
 await page.getByRole('button',{name:'Switch theme'}).click();
 assert.equal(await page.locator('html').evaluate(e=>e.classList.contains('dark')),true);
 await page.screenshot({path:fileURLToPath(new URL('../docs/screenshots/observability-dark.png',import.meta.url))});
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 disconnected=true;
 await page.getByText('Reconnecting',{exact:true}).waitFor();
 assert.ok(await list.locator('tbody tr').count()>0);
 assert.deepEqual(failures,[]);
 console.log('PASS filters, pagination, inspector, pause/resume, range, sorting, themes, mobile containment, disconnect');
} finally {await browser.close();}
